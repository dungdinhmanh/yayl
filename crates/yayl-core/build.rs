//! Generates the protocol facts from `launcher-versions.lock.json`.
//!
//! That file is refreshed by `scripts/check-launcher-versions.mjs` from the
//! public update feed and, with `--extract`, from the published installer, so
//! the values below never need a code change. The output lands in `OUT_DIR`:
//! it is rebuilt from the lock on every fresh build and never committed.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const LAUNCHERS: [(&str, &str); 2] = [("arknights", "ARKNIGHTS"), ("stella", "STELLA")];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let lock_path = manifest
        .join("..")
        .join("..")
        .join("launcher-versions.lock.json");
    println!("cargo:rerun-if-changed={}", lock_path.display());

    let text = fs::read_to_string(&lock_path)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", lock_path.display()));
    let lock: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|error| panic!("cannot parse {}: {error}", lock_path.display()));

    let mut generated =
        String::from("// Generated by build.rs from launcher-versions.lock.json.\n");
    for (id, prefix) in LAUNCHERS {
        let version = field(&lock, id, "version");
        let salt = field(&lock, id, "authSalt");
        assert!(
            salt.len() == 32 && salt.chars().all(|c| c.is_ascii_hexdigit()),
            "launcher-versions.lock.json: {id}.authSalt must be 32 hex characters"
        );
        writeln!(
            generated,
            "pub const {prefix}_PROTOCOL_VERSION: &str = {version:?};"
        )
        .expect("write generated constants");
        writeln!(generated, "pub const {prefix}_AUTH_SALT: &str = {salt:?};")
            .expect("write generated constants");
    }

    // Both EN launchers share one host, and the regions differ only in the
    // region code, so a single host is emitted and JP/KR are derived from it.
    let en = field(&lock, "arknights", "apiBase");
    assert_eq!(
        en,
        field(&lock, "stella", "apiBase"),
        "launcher-versions.lock.json: the EN launchers disagree on the API host"
    );
    assert!(
        en.contains("-en."),
        "launcher-versions.lock.json: arknights.apiBase has no -en. region code"
    );
    // The host is compiled into every build and receives signed requests, so a
    // refreshed lock must not be able to point it at another domain.
    let host = en.strip_prefix("https://").unwrap_or_else(|| {
        panic!("launcher-versions.lock.json: arknights.apiBase must start with https://")
    });
    assert!(
        host.ends_with(".yo-star.com")
            && host
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-'),
        "launcher-versions.lock.json: arknights.apiBase must be a bare https://*.yo-star.com host \
         (no path, port or credentials)"
    );
    writeln!(generated, "pub const API_HOST_EN: &str = {en:?};")
        .expect("write generated constants");
    for (code, name) in [("jp", "JP"), ("kr", "KR")] {
        let host = en.replace("-en.", &format!("-{code}."));
        writeln!(generated, "pub const API_HOST_{name}: &str = {host:?};")
            .expect("write generated constants");
    }

    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("launcher_facts.rs");
    fs::write(out, generated).expect("write launcher facts");
}

fn field(lock: &serde_json::Value, id: &str, name: &str) -> String {
    lock["launchers"][id][name]
        .as_str()
        .unwrap_or_else(|| panic!("launcher-versions.lock.json: {id}.{name} is missing"))
        .to_owned()
}
